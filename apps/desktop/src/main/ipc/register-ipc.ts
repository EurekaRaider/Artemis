import type { ApplicationServices } from "../application/application-services.js";
export function registerIpc(services: ApplicationServices): void {
  registerProjectInstructionsIpc(services);
  registerComputerIpc(services);
  registerHooksIpc(services);
  registerConversationHistoryIpc(services);
  registerImIpc(services);
  registerAppearanceIpc(services);
  registerPreferencesIpc(services);
  registerUpdatesDiagnosticsIpc(services);
  registerModelsProvidersIpc(services);
  registerCustomAgentsIpc(services);
  registerConfigurationImportIpc(services);
  registerMcpIpc(services);
  registerResourceCatalogIpc(services);
  registerComputerRuntimeIpc(services);
  registerPluginCatalogIpc(services);
  registerConnectorsIpc(services);
  registerPluginManagementIpc(services);
  registerExtensionsIpc(services);
  registerTerminalIpc(services);
  let designCapability: ReturnType<typeof registerDesignCapabilityIpc>;
  registerWorkspacePreviewIpc(services, () =>
    designCapability.ensureDesignPackSynced(),
  );
  registerOfficeIpc(services);
  designCapability = registerDesignCapabilityIpc(services);
  registerWorkspaceFilesIpc(services);
  registerProjectGitIpc(services);
  registerAttachmentsIpc(services);
  registerThreadsIpc(services);
  registerGoalsIpc(services);
  registerThreadMaintenanceIpc(services);
  registerWorktreesIpc(services);
  registerProviderLoginIpc(services);
  registerTurnsIpc(services);
  registerInteractionResolutionIpc(services);
  registerAutomationsIpc(services);
  registerReviewIpc(services);
}
