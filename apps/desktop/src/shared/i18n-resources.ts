export type TranslationNamespace = keyof NamespaceCatalog;

const TRANSLATED_BY_SOURCE = Object.fromEntries(
  APP_LOCALES.map((locale) => {
    const phrases = new Map<string, string>();
    for (const namespace of Object.keys(en) as TranslationNamespace[]) {
      for (const [key, source] of Object.entries(en[namespace])) {
        phrases.set(
          source,
          (I18N_RESOURCES[locale][namespace] as Record<string, string>)[key] ??
            source,
        );
      }
    }
    return [locale, phrases];
  }),
) as unknown as Record<AppLocale, ReadonlyMap<string, string>>;

export function localizedCopy<T extends Record<string, unknown>>(
  locale: AppLocale,
  namespace: TranslationNamespace,
  fallback: T,
): T {
  const direct = I18N_RESOURCES[locale][namespace] as Record<string, string>;
  const translatedBySource = TRANSLATED_BY_SOURCE[locale];
  return Object.fromEntries(
    Object.entries(fallback).map(([key, value]) => [
      key,
      direct[key] ??
        (typeof value === "string"
          ? (translatedBySource.get(value) ?? value)
          : value),
    ]),
  ) as T;
}
