export type TranslationNamespace = keyof NamespaceCatalog;

// Only reuse a phrase across namespaces when all of its translations agree.
const UNAMBIGUOUS_TRANSLATIONS = Object.fromEntries(
  APP_LOCALES.map((locale) => {
    const phrases = new Map<string, string | undefined>();
    for (const namespace of Object.keys(en) as TranslationNamespace[]) {
      for (const [key, source] of Object.entries(en[namespace])) {
        const translated = (
          I18N_RESOURCES[locale][namespace] as Record<string, string>
        )[key]!;
        phrases.set(
          source,
          phrases.has(source) && phrases.get(source) !== translated
            ? undefined
            : translated,
        );
      }
    }
    return [locale, phrases];
  }),
) as unknown as Record<AppLocale, ReadonlyMap<string, string | undefined>>;

const TRANSLATED_BY_SOURCE = Object.fromEntries(
  APP_LOCALES.map((locale) => {
    return [
      locale,
      Object.fromEntries(
        (Object.keys(en) as TranslationNamespace[]).map((namespace) => [
          namespace,
          new Map(
            Object.entries(en[namespace]).map(([key, source]) => [
              source,
              (I18N_RESOURCES[locale][namespace] as Record<string, string>)[
                key
              ]!,
            ]),
          ),
        ]),
      ),
    ];
  }),
) as unknown as Record<
  AppLocale,
  Record<TranslationNamespace, ReadonlyMap<string, string>>
>;

export function localizedCopy<T extends Record<string, unknown>>(
  locale: AppLocale,
  namespace: TranslationNamespace,
  fallback: T,
): T {
  if (locale === "en") return fallback;
  const source = en[namespace] as Record<string, string>;
  const direct = I18N_RESOURCES[locale][namespace] as Record<string, string>;
  const translatedBySource = TRANSLATED_BY_SOURCE[locale];
  return Object.fromEntries(
    Object.entries(fallback).map(([key, value]) => {
      if (typeof value !== "string") return [key, value];
      // A shared key does not imply a shared meaning (e.g. tool running vs. thinking).
      return [
        key,
        source[key] === value
          ? direct[key]
          : (translatedBySource[namespace].get(value) ??
            translatedBySource.common.get(value) ??
            UNAMBIGUOUS_TRANSLATIONS[locale].get(value) ??
            value),
      ];
    }),
  ) as T;
}
