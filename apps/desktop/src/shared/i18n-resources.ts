function fromArrays(
  translation: (typeof translations)[keyof typeof translations],
): NamespaceCatalog {
  return Object.fromEntries(
    (Object.keys(en) as Array<keyof typeof en>).map((namespace) => {
      const keys = Object.keys(en[namespace]);
      const values = translation[namespace];
      if (keys.length !== values.length) {
        throw new Error(`Invalid ${namespace} translation resource length.`);
      }
      return [
        namespace,
        Object.fromEntries(keys.map((key, index) => [key, values[index]])),
      ];
    }),
  ) as NamespaceCatalog;
}

